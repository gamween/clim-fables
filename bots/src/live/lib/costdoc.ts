// The "Gas and cost" section of docs/integrate/README.md, rendered from docs/evidence/gas-robinhood-testnet.json so no
// published number is typed by hand (pure helpers; scripts/cost-doc.ts writes or checks the file).
import type { Cadence, GasSummary } from "./gas";

export const COST_BEGIN = "<!-- clim:cost:begin -->";
export const COST_END = "<!-- clim:cost:end -->";

export type GasEvidence = {
  generatedAt: string;
  chainId: number;
  deskReport: GasSummary | null;
  poke: GasSummary | null;
  keeperPoke: GasSummary | null;
  arbSwap: GasSummary | null;
  retailSwap: GasSummary | null;
  cadence?: { fromBlock: number; toBlock: number; deskReport: Cadence | null; poke: Cadence | null };
};

const ROWS: Array<[keyof Pick<GasEvidence, "deskReport" | "poke" | "keeperPoke" | "arbSwap" | "retailSwap">, string]> = [
  ["deskReport", "Desk report (CRE simulator, through the mock forwarder)"],
  ["poke", "`ClimPoker.poke()` on pool D"],
  ["keeperPoke", "Keeper-style `pokeFee` on pool K"],
  ["arbSwap", "Arbitrage swap"],
  ["retailSwap", "Retail swap"],
];

const int = (n: number): string => n.toLocaleString("en-US");

/** An ETH amount with no exponent and no trailing zeros (8.6297e-7 -> "0.00000086297"). */
export function formatEth(x: number): string {
  const s = x.toFixed(12).replace(/0+$/, "");
  return s.endsWith(".") ? `${s}0` : s;
}

export function renderCostSection(e: GasEvidence): string {
  const c = e.cadence;
  if (c === undefined || c.deskReport === null || c.poke === null) {
    throw new Error("docs/evidence/gas-robinhood-testnet.json has no cadence: run `cd bots && bun run live:gas` first");
  }
  if (e.deskReport === null || e.poke === null) throw new Error("the evidence file has no desk report or poke receipt");
  const lines = [
    `_Generated by \`cd bots && bun run live:cost-doc\` from \`docs/evidence/gas-robinhood-testnet.json\` (generated ${e.generatedAt}, chain ${e.chainId}). Do not edit by hand._`,
    "",
    "| Transaction | Receipts | Gas, median | Gas, p90 | L1 gas, median | Cost at the median gas price |",
    "|---|---|---|---|---|---|",
  ];
  for (const [key, label] of ROWS) {
    const s = e[key];
    lines.push(s === null ? `| ${label} | 0 | not measured | | | |` : `| ${label} | ${int(s.n)} | ${int(s.gasUsedMedian)} | ${int(s.gasUsedP90)} | ${int(s.gasUsedForL1Median)} | ${formatEth(s.costMedianEth)} ETH |`);
  }
  const gwei = e.deskReport.effectiveGasPriceMedianWei / 1e9;
  const perDayEth = e.deskReport.costMedianEth * c.deskReport.perDay + e.poke.costMedianEth * c.poke.perDay;
  lines.push(
    "",
    `Median effective gas price of the desk reports: ${gwei} gwei.`,
    "",
    `Cadence, read from the chain over blocks ${int(c.fromBlock)} to ${int(c.toBlock)} (outages included): ${int(c.deskReport.n)} desk reports, a median gap of ${c.deskReport.medianGapSec} s (p90 ${c.deskReport.p90GapSec} s), ${int(c.deskReport.perDay)} reports a day; ${int(c.poke.n)} pokes, ${int(c.poke.perDay)} a day.`,
    "",
    `At that cadence and the median costs, the desk and its poker cost ${perDayEth.toPrecision(2)} ETH a day on Robinhood Chain testnet.`,
  );
  return lines.join("\n");
}

/** Replaces what sits between the two markers (markers kept); throws if either is missing. */
export function replaceBetween(doc: string, body: string, begin: string = COST_BEGIN, end: string = COST_END): string {
  const a = doc.indexOf(begin);
  const b = doc.indexOf(end);
  if (a === -1 || b === -1 || b < a) throw new Error(`markers ${begin} ... ${end} not found`);
  return `${doc.slice(0, a + begin.length)}\n${body}\n${doc.slice(b)}`;
}
